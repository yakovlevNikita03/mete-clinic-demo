<?php
/**
 * Specialists archive.
 *
 * @package Mete_Clinic
 */

get_header();
?>
<main id="main" tabindex="-1">
	<section class="section">
		<div class="container">
			<div class="page-head">
				<p class="eyebrow"><?php esc_html_e( 'Команда', 'mete-clinic' ); ?></p>
				<h1 class="section__title"><?php esc_html_e( 'Наши специалисты', 'mete-clinic' ); ?></h1>
			</div>

			<?php if ( have_posts() ) : ?>
				<div class="team-grid">
					<?php
					while ( have_posts() ) :
						the_post();

						$mete_id      = get_the_ID();
						$mete_name    = get_the_title();
						$mete_role    = mete_specialist_role( $mete_id );
						$mete_booking = mete_booking_url( $mete_id );
						$mete_link    = mete_is_http_url( $mete_booking );
						$mete_photo   = get_the_post_thumbnail( $mete_id, 'mete-portrait', array(
							'class'   => 'team-card__photo',
							'alt'     => sprintf(
								/* translators: %s: specialist name. */
								__( 'Фото: %s', 'mete-clinic' ),
								$mete_name
							),
							'loading' => 'lazy',
						) );
						?>
						<?php if ( $mete_link ) : ?>
							<a class="team-card team-card--link reveal" href="<?php echo esc_url( $mete_booking ); ?>" target="_blank" rel="noopener noreferrer">
						<?php else : ?>
							<article class="team-card reveal">
						<?php endif; ?>

							<div class="team-card__media">
								<?php if ( '' !== $mete_photo ) : ?>
									<?php echo $mete_photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core. ?>
								<?php else : ?>
									<span class="team-card__monogram" aria-hidden="true"><?php echo esc_html( mete_initials( $mete_name ) ); ?></span>
								<?php endif; ?>
							</div>

							<h2 class="team-card__name"><?php echo esc_html( $mete_name ); ?></h2>

							<?php if ( '' !== $mete_role ) : ?>
								<p class="team-card__role"><?php echo esc_html( $mete_role ); ?></p>
							<?php endif; ?>

						<?php if ( $mete_link ) : ?>
							</a>
						<?php else : ?>
							</article>
						<?php endif; ?>
						<?php
					endwhile;
					?>
				</div>
			<?php else : ?>
				<p class="catalog-empty"><?php esc_html_e( 'Специалисты скоро появятся.', 'mete-clinic' ); ?></p>
			<?php endif; ?>
		</div>
	</section>
</main>
<?php
get_footer();
