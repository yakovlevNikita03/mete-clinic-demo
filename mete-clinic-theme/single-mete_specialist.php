<?php
/**
 * Single specialist.
 *
 * @package Mete_Clinic
 */

get_header();

while ( have_posts() ) :
	the_post();

	$mete_id         = get_the_ID();
	$mete_name       = get_the_title();
	$mete_role       = mete_specialist_role( $mete_id );
	$mete_experience = mete_specialist_experience( $mete_id );
	$mete_education  = mete_specialist_education( $mete_id );
	$mete_booking    = mete_booking_url( $mete_id );
	$mete_photo      = get_the_post_thumbnail( $mete_id, 'mete-portrait', array(
		'class'   => 'team-card__photo',
		'loading' => 'eager',
	) );
	?>
	<main id="main" tabindex="-1">
		<section class="section">
			<div class="container">
				<p class="back-link">
					<a href="<?php echo esc_url( home_url( '/#team' ) ); ?>">&larr; <?php esc_html_e( 'Наши специалисты', 'mete-clinic' ); ?></a>
				</p>

				<div class="single-grid">
					<div class="single-grid__media">
						<div class="team-card__media team-card__media--static">
							<?php if ( '' !== $mete_photo ) : ?>
								<?php echo $mete_photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core. ?>
							<?php else : ?>
								<span class="team-card__monogram" aria-hidden="true"><?php echo esc_html( mete_initials( $mete_name ) ); ?></span>
							<?php endif; ?>
						</div>
					</div>

					<div class="single-grid__body">
						<?php if ( '' !== $mete_role ) : ?>
							<p class="eyebrow"><?php echo esc_html( $mete_role ); ?></p>
						<?php endif; ?>

						<h1 class="section__title"><?php echo esc_html( $mete_name ); ?></h1>

						<?php if ( '' !== $mete_experience ) : ?>
							<dl class="detail-list">
								<dt><?php esc_html_e( 'Опыт работы', 'mete-clinic' ); ?></dt>
								<dd><?php echo esc_html( $mete_experience ); ?></dd>
							</dl>
						<?php endif; ?>

						<?php if ( '' !== $mete_education ) : ?>
							<dl class="detail-list">
								<dt><?php esc_html_e( 'Образование и квалификация', 'mete-clinic' ); ?></dt>
								<dd><?php echo nl2br( esc_html( $mete_education ) ); ?></dd>
							</dl>
						<?php endif; ?>

						<?php $mete_body = trim( wp_strip_all_tags( (string) get_the_content() ) ); ?>
						<?php if ( '' !== $mete_body ) : ?>
							<div class="page-content">
								<?php the_content(); ?>
							</div>
						<?php endif; ?>

						<div class="single-actions">
							<?php
							echo mete_link(
								$mete_booking,
								esc_html__( 'Записаться к специалисту', 'mete-clinic' ),
								array( 'class' => 'btn btn--primary' )
							);
							?>
						</div>
					</div>
				</div>
			</div>
		</section>
	</main>
	<?php
endwhile;

get_footer();
