<?php
/**
 * Single service.
 *
 * @package Mete_Clinic
 */

get_header();

while ( have_posts() ) :
	the_post();

	$mete_id       = get_the_ID();
	$mete_price    = mete_price_text( $mete_id );
	$mete_note     = mete_price_note( $mete_id );
	$mete_duration = mete_duration_text( $mete_id );
	$mete_cats     = wp_list_pluck( mete_service_categories_for( $mete_id ), 'name' );
	$mete_image    = get_the_post_thumbnail( $mete_id, 'large', array(
		'class'   => 'single-grid__image',
		'loading' => 'eager',
	) );
	?>
	<main id="main" tabindex="-1">
		<section class="section">
			<div class="container">
				<p class="back-link">
					<a href="<?php echo esc_url( mete_catalog_url() ); ?>">&larr; <?php esc_html_e( 'Все услуги', 'mete-clinic' ); ?></a>
				</p>

				<div class="single-grid">
					<?php if ( '' !== $mete_image ) : ?>
						<div class="single-grid__media"><?php echo $mete_image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core. ?></div>
					<?php endif; ?>

					<div class="single-grid__body">
						<?php if ( ! empty( $mete_cats ) ) : ?>
							<p class="eyebrow"><?php echo esc_html( implode( ' · ', $mete_cats ) ); ?></p>
						<?php endif; ?>

						<h1 class="section__title"><?php the_title(); ?></h1>

						<?php if ( '' !== $mete_price ) : ?>
							<p class="single-price"><?php echo esc_html( $mete_price ); ?></p>
						<?php endif; ?>

						<?php if ( '' !== $mete_note ) : ?>
							<p class="single-note"><?php echo esc_html( $mete_note ); ?></p>
						<?php endif; ?>

						<?php if ( '' !== $mete_duration ) : ?>
							<p class="single-meta"><?php esc_html_e( 'Продолжительность:', 'mete-clinic' ); ?> <?php echo esc_html( $mete_duration ); ?></p>
						<?php endif; ?>

						<?php if ( has_excerpt() ) : ?>
							<p class="single-lead"><?php echo esc_html( wp_strip_all_tags( get_the_excerpt() ) ); ?></p>
						<?php endif; ?>

						<div class="page-content">
							<?php the_content(); ?>
						</div>

						<div class="single-actions">
							<?php
							echo mete_link(
								mete_booking_url( $mete_id ),
								esc_html__( 'Записаться на процедуру', 'mete-clinic' ),
								array( 'class' => 'btn btn--primary' )
							);
							?>
						</div>
					</div>
				</div>
			</div>
		</section>
	</main>
	<?php
endwhile;

get_footer();
