<?php
/**
 * Home page: specialists.
 *
 * @package Mete_Clinic
 */

if ( ! mete_plugin_active() ) {
	return;
}

$mete_team = mete_specialists();

if ( ! $mete_team->have_posts() ) {
	wp_reset_postdata();

	return;
}

$mete_has_photos = false;
?>
<section class="section" id="team" aria-labelledby="team-title">
	<div class="container">
		<div class="section__head">
			<div>
				<p class="eyebrow"><?php esc_html_e( 'Команда профессионалов', 'mete-clinic' ); ?></p>
				<h2 class="section__title" id="team-title"><?php esc_html_e( 'Наши специалисты', 'mete-clinic' ); ?></h2>
			</div>
		</div>

		<div class="team-grid">
			<?php
			while ( $mete_team->have_posts() ) :
				$mete_team->the_post();

				$mete_id      = get_the_ID();
				$mete_name    = get_the_title();
				$mete_role    = mete_specialist_role( $mete_id );
				$mete_booking = mete_booking_url( $mete_id );
				$mete_link    = mete_is_http_url( $mete_booking );
				$mete_photo   = get_the_post_thumbnail( $mete_id, 'mete-portrait', array(
					'class'   => 'team-card__photo',
					'alt'     => sprintf(
						/* translators: %s: specialist name. */
						__( 'Фото: %s', 'mete-clinic' ),
						$mete_name
					),
					'loading' => 'lazy',
				) );

				if ( '' !== $mete_photo ) {
					$mete_has_photos = true;
				}
				?>
				<?php if ( $mete_link ) : ?>
					<a class="team-card team-card--link reveal" href="<?php echo esc_url( $mete_booking ); ?>" target="_blank" rel="noopener noreferrer">
				<?php else : ?>
					<article class="team-card reveal">
				<?php endif; ?>

					<div class="team-card__media">
						<?php if ( '' !== $mete_photo ) : ?>
							<?php echo $mete_photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core. ?>
						<?php else : ?>
							<span class="team-card__monogram" aria-hidden="true"><?php echo esc_html( mete_initials( $mete_name ) ); ?></span>
						<?php endif; ?>
					</div>

					<h3 class="team-card__name"><?php echo esc_html( $mete_name ); ?></h3>

					<?php if ( '' !== $mete_role ) : ?>
						<p class="team-card__role"><?php echo esc_html( $mete_role ); ?></p>
					<?php endif; ?>

					<?php if ( $mete_link ) : ?>
						<span class="team-card__profile">
							<?php esc_html_e( 'Запись и профиль', 'mete-clinic' ); ?>
							<span class="team-card__profile-arrow" aria-hidden="true"><?php echo mete_icon( 'arrow' ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped ?></span>
						</span>
					<?php endif; ?>

				<?php if ( $mete_link ) : ?>
					</a>
				<?php else : ?>
					</article>
				<?php endif; ?>
			<?php endwhile; ?>
			<?php wp_reset_postdata(); ?>
		</div>

		<?php if ( ! $mete_has_photos ) : ?>
			<p class="team-note"><?php esc_html_e( 'Фотографии специалистов появятся после получения материалов от клиники.', 'mete-clinic' ); ?></p>
		<?php endif; ?>
	</div>
</section>
