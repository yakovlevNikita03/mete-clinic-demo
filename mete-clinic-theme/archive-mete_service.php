<?php
/**
 * Full service catalog.
 *
 * @package Mete_Clinic
 */

get_header();

$mete_terms   = mete_service_filters();
$mete_current = mete_current_category_slug();
$mete_all_url = mete_catalog_url();
$mete_total   = mete_published_services_count();
$mete_args    = array(
	'posts_per_page' => -1,
	'no_found_rows'  => true,
);

if ( '' !== $mete_current ) {
	$mete_args['tax_query'] = array(
		array(
			'taxonomy' => 'mete_service_cat',
			'field'    => 'slug',
			'terms'    => $mete_current,
		),
	);
}

$mete_query = mete_services( $mete_args );
$mete_found = $mete_query->have_posts();
?>
<main id="main" tabindex="-1">
	<section class="section" id="catalog">
		<div class="container">
			<div class="page-head">
				<p class="eyebrow"><?php esc_html_e( 'Прайс клиники', 'mete-clinic' ); ?></p>
				<h1 class="section__title"><?php esc_html_e( 'Каталог услуг', 'mete-clinic' ); ?></h1>
				<p class="page-head__lead"><?php esc_html_e( 'Все услуги клиники с ценами. Запись — онлайн через Yclients, по телефону или в мессенджере.', 'mete-clinic' ); ?></p>
			</div>

			<?php if ( ! empty( $mete_terms ) ) : ?>
				<nav class="catalog-filters" aria-label="<?php esc_attr_e( 'Категории услуг', 'mete-clinic' ); ?>">
					<a class="chip<?php echo '' === $mete_current ? ' is-active' : ''; ?>" href="<?php echo esc_url( $mete_all_url ); ?>"<?php echo '' === $mete_current ? ' aria-current="page"' : ''; ?>>
						<?php esc_html_e( 'Все услуги', 'mete-clinic' ); ?>
						<span class="chip__count"><?php echo esc_html( number_format_i18n( $mete_total ) ); ?></span>
					</a>
					<?php foreach ( $mete_terms as $mete_term ) : ?>
						<?php $mete_active = ( $mete_current === $mete_term->slug ); ?>
						<a class="chip<?php echo $mete_active ? ' is-active' : ''; ?>" href="<?php echo esc_url( mete_category_link( $mete_term ) ); ?>"<?php echo $mete_active ? ' aria-current="page"' : ''; ?>>
							<?php echo esc_html( $mete_term->name ); ?>
							<span class="chip__count"><?php echo esc_html( number_format_i18n( (int) $mete_term->count ) ); ?></span>
						</a>
					<?php endforeach; ?>
				</nav>
			<?php endif; ?>

			<?php if ( $mete_found ) : ?>
				<ul class="catalog-list">
					<?php
					while ( $mete_query->have_posts() ) :
						$mete_query->the_post();

						$mete_id       = get_the_ID();
						$mete_price    = mete_price_text( $mete_id );
						$mete_note     = mete_price_note( $mete_id );
						$mete_duration = mete_duration_text( $mete_id );
						$mete_excerpt  = trim( wp_strip_all_tags( get_the_excerpt() ) );
						$mete_cats     = mete_service_categories_for( $mete_id );
						$mete_image    = get_the_post_thumbnail( $mete_id, 'mete-card', array(
							'class'   => 'catalog-item__image',
							'loading' => 'lazy',
						) );
						?>
						<li class="catalog-item<?php echo '' === $mete_image ? ' catalog-item--no-media' : ''; ?>">
							<?php if ( '' !== $mete_image ) : ?>
								<div class="catalog-item__media"><?php echo $mete_image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core. ?></div>
							<?php endif; ?>

							<div class="catalog-item__body">
								<?php if ( ! empty( $mete_cats ) ) : ?>
									<p class="catalog-item__cat">
										<?php
										$mete_cat_links = array();

										foreach ( $mete_cats as $mete_cat ) {
											$mete_cat_links[] = '<a href="' . esc_url( mete_category_link( $mete_cat ) ) . '">' . esc_html( $mete_cat->name ) . '</a>';
										}

										echo implode( ' <span aria-hidden="true">·</span> ', $mete_cat_links ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped above.
										?>
									</p>
								<?php endif; ?>

								<h2 class="catalog-item__title">
									<a href="<?php the_permalink(); ?>"><?php the_title(); ?></a>
								</h2>

								<?php if ( '' !== $mete_excerpt ) : ?>
									<p class="catalog-item__text"><?php echo esc_html( $mete_excerpt ); ?></p>
								<?php endif; ?>

								<?php if ( '' !== $mete_duration ) : ?>
									<p class="catalog-item__meta"><?php esc_html_e( 'Продолжительность:', 'mete-clinic' ); ?> <?php echo esc_html( $mete_duration ); ?></p>
								<?php endif; ?>
							</div>

							<div class="catalog-item__side">
								<?php if ( '' !== $mete_price ) : ?>
									<span class="catalog-item__price"><?php echo esc_html( $mete_price ); ?></span>
								<?php else : ?>
									<span class="catalog-item__price catalog-item__price--empty"><?php esc_html_e( 'Цена по запросу', 'mete-clinic' ); ?></span>
								<?php endif; ?>

								<?php if ( '' !== $mete_note ) : ?>
									<span class="catalog-item__note"><?php echo esc_html( $mete_note ); ?></span>
								<?php endif; ?>

								<?php
								echo mete_link(
									mete_booking_url( $mete_id ),
									esc_html__( 'Записаться', 'mete-clinic' ),
									array( 'class' => 'btn btn--primary catalog-item__action' )
								);
								?>
							</div>
						</li>
						<?php
					endwhile;
					wp_reset_postdata();
					?>
				</ul>
			<?php else : ?>
				<p class="catalog-empty"><?php esc_html_e( 'В этой категории пока нет опубликованных услуг.', 'mete-clinic' ); ?></p>
			<?php endif; ?>
		</div>
	</section>
</main>
<?php
get_footer();
